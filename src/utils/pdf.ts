import jsPDF from 'jspdf';
import autoTable from 'jspdf-autotable';
import html2canvas from 'html2canvas';
import { formatDate } from '@/lib/format';

export interface PdfKpiItem {
  label: string;
  value: string;
  subtitle?: string;
  isPositive?: boolean;
  isNegative?: boolean;
}

export interface PdfTableColumn {
  header: string;
  dataKey: string;
  align?: 'left' | 'center' | 'right';
  width?: number;
}

export interface CreatePdfOptions {
  title: string;
  subtitle?: string;
  period?: string;
  clientFilter?: string;
  generatedBy?: string;
  orientation?: 'portrait' | 'landscape';
}

// In-memory font cache so we only load TTF once
let fontLoaded = false;
let regularFontBase64 = '';
let boldFontBase64 = '';

/**
 * Loads and registers the custom Montserrat TTF fonts supporting Indian Rupee (₹).
 */
export async function ensureMontserratFonts(doc: jsPDF): Promise<boolean> {
  try {
    if (!fontLoaded) {
      const [regRes, boldRes] = await Promise.all([
        fetch('/fonts/Montserrat-Regular.ttf').catch(() => null),
        fetch('/fonts/Montserrat-Bold.ttf').catch(() => null),
      ]);

      if (regRes && regRes.ok) {
        const regBuf = await regRes.arrayBuffer();
        regularFontBase64 = arrayBufferToBase64(regBuf);
      }
      if (boldRes && boldRes.ok) {
        const boldBuf = await boldRes.arrayBuffer();
        boldFontBase64 = arrayBufferToBase64(boldBuf);
      }
      if (regularFontBase64) {
        fontLoaded = true;
      }
    }

    if (regularFontBase64) {
      doc.addFileToVFS('Montserrat-Regular.ttf', regularFontBase64);
      doc.addFont('Montserrat-Regular.ttf', 'Montserrat', 'normal');
      if (boldFontBase64) {
        doc.addFileToVFS('Montserrat-Bold.ttf', boldFontBase64);
        doc.addFont('Montserrat-Bold.ttf', 'Montserrat', 'bold');
      } else {
        doc.addFont('Montserrat-Regular.ttf', 'Montserrat', 'bold');
      }
      doc.setFont('Montserrat', 'normal');
      return true;
    }
  } catch (err) {
    console.warn('Montserrat TTF embedding failed, falling back to Helvetica:', err);
  }

  doc.setFont('helvetica', 'normal');
  return false;
}

function arrayBufferToBase64(buffer: ArrayBuffer): string {
  let binary = '';
  const bytes = new Uint8Array(buffer);
  const len = bytes.byteLength;
  for (let i = 0; i < len; i++) {
    binary += String.fromCharCode(bytes[i]);
  }
  return window.btoa(binary);
}

/**
 * Creates a brand-styled jsPDF instance with metadata.
 */
export async function createPdfDoc(options: CreatePdfOptions): Promise<jsPDF> {
  const orientation = options.orientation || 'portrait';
  const doc = new jsPDF({
    orientation,
    unit: 'mm',
    format: 'a4',
  });

  await ensureMontserratFonts(doc);
  return doc;
}

/**
 * Draws the top agency branded header.
 * Returns the Y position where content can begin.
 */
export function addHeader(doc: jsPDF, options: CreatePdfOptions): number {
  const pageWidth = doc.internal.pageSize.getWidth();
  const font = fontLoaded ? 'Montserrat' : 'helvetica';

  // Brand Header Bar Accent
  doc.setFillColor(5, 150, 105); // emerald-600 #059669
  doc.rect(0, 0, pageWidth, 4, 'F');

  // Agency Brand Title
  doc.setFont(font, 'bold');
  doc.setFontSize(16);
  doc.setTextColor(15, 23, 42); // slate-900
  doc.text('GETUP AGENCY', 14, 15);

  // Agency Sub-brand
  doc.setFont(font, 'normal');
  doc.setFontSize(8);
  doc.setTextColor(100, 116, 139); // slate-500
  doc.text('Control Panel & Performance Intelligence', 14, 19);

  // Report Title (Right or Below)
  doc.setFont(font, 'bold');
  doc.setFontSize(14);
  doc.setTextColor(5, 150, 105);
  doc.text(options.title, 14, 28);

  // Metadata block (Period, Client, Generated At, Generated By)
  doc.setFont(font, 'normal');
  doc.setFontSize(9);
  doc.setTextColor(71, 85, 105); // slate-600

  let metaParts: string[] = [];
  if (options.period) metaParts.push(`Period: ${options.period}`);
  if (options.clientFilter && options.clientFilter !== 'all') {
    metaParts.push(`Client: ${options.clientFilter}`);
  }
  metaParts.push(`Generated: ${formatDate(new Date().toISOString())}`);
  if (options.generatedBy) metaParts.push(`By: ${options.generatedBy}`);

  doc.text(metaParts.join('  |  '), 14, 33);

  // Thin dividing line
  doc.setDrawColor(226, 232, 240); // slate-200
  doc.setLineWidth(0.4);
  doc.line(14, 36, pageWidth - 14, 36);

  return 42; // Next available Y coordinate
}

/**
 * Renders a row of KPI stat boxes.
 * Returns the Y position after the KPI block.
 */
export function addKpiRow(doc: jsPDF, startY: number, kpis: PdfKpiItem[]): number {
  if (!kpis || kpis.length === 0) return startY;
  const pageWidth = doc.internal.pageSize.getWidth();
  const font = fontLoaded ? 'Montserrat' : 'helvetica';
  const margin = 14;
  const availableWidth = pageWidth - margin * 2;
  const count = kpis.length;
  const gap = 3;
  const boxWidth = (availableWidth - gap * (count - 1)) / count;
  const boxHeight = 16;

  kpis.forEach((kpi, idx) => {
    const x = margin + idx * (boxWidth + gap);

    // Box background
    doc.setFillColor(248, 250, 252); // slate-50
    doc.setDrawColor(226, 232, 240); // slate-200
    doc.setLineWidth(0.2);
    doc.roundedRect(x, startY, boxWidth, boxHeight, 1.5, 1.5, 'FD');

    // Label
    doc.setFont(font, 'normal');
    doc.setFontSize(7);
    doc.setTextColor(100, 116, 139);
    doc.text(kpi.label.toUpperCase(), x + 3, startY + 4.5);

    // Value
    doc.setFont(font, 'bold');
    doc.setFontSize(10);
    if (kpi.isPositive) {
      doc.setTextColor(5, 150, 105);
    } else if (kpi.isNegative) {
      doc.setTextColor(225, 29, 72);
    } else {
      doc.setTextColor(15, 23, 42);
    }

    // Replace Rupee if font doesn't support ₹
    const displayValue = fontLoaded ? kpi.value : kpi.value.replace(/₹/g, 'Rs. ');
    doc.text(displayValue, x + 3, startY + 10.5);

    // Optional Subtitle
    if (kpi.subtitle) {
      doc.setFont(font, 'normal');
      doc.setFontSize(6.5);
      doc.setTextColor(148, 163, 184);
      doc.text(kpi.subtitle, x + 3, startY + 14);
    }
  });

  return startY + boxHeight + 6;
}

/**
 * Embeds a chart image into the document.
 */
export async function addChartElement(
  doc: jsPDF,
  startY: number,
  element: HTMLElement | null,
  maxHeight: number = 60
): Promise<number> {
  if (!element) return startY;
  try {
    const canvas = await html2canvas(element, {
      scale: 2,
      useCORS: true,
      logging: false,
      backgroundColor: '#ffffff',
    });

    const imgData = canvas.toDataURL('image/png');
    const pageWidth = doc.internal.pageSize.getWidth();
    const margin = 14;
    const availableWidth = pageWidth - margin * 2;

    const imgWidth = availableWidth;
    const imgHeight = Math.min(maxHeight, (canvas.height * imgWidth) / canvas.width);

    // Check page overflow
    const pageHeight = doc.internal.pageSize.getHeight();
    if (startY + imgHeight > pageHeight - 20) {
      doc.addPage();
      startY = 20;
    }

    doc.addImage(imgData, 'PNG', margin, startY, imgWidth, imgHeight);
    return startY + imgHeight + 6;
  } catch (err) {
    console.warn('Chart capture skipped:', err);
    return startY;
  }
}

/**
 * Embeds an autotable with repeating headers, right-aligned numbers, and totals styling.
 */
export function addTable(
  doc: jsPDF,
  startY: number,
  columns: PdfTableColumn[],
  rows: (string | number)[][],
  options?: {
    hasTotalsRow?: boolean;
    emptyText?: string;
  }
): number {
  const font = fontLoaded ? 'Montserrat' : 'helvetica';

  if (rows.length === 0) {
    doc.setFont(font, 'italic');
    doc.setFontSize(9);
    doc.setTextColor(100, 116, 139);
    doc.text(options?.emptyText || 'No records available for the selected period.', 14, startY + 6);
    return startY + 14;
  }

  // Determine column alignments
  const columnStyles: Record<number, { halign: 'left' | 'center' | 'right'; cellWidth?: number }> = {};
  columns.forEach((col, idx) => {
    columnStyles[idx] = {
      halign: col.align || 'left',
      cellWidth: col.width,
    };
  });

  // Prepare table data with rupee fallback if font not loaded
  const formattedRows = rows.map((row) =>
    row.map((cell) => {
      const str = String(cell ?? '');
      return fontLoaded ? str : str.replace(/₹/g, 'Rs. ');
    })
  );

  autoTable(doc, {
    startY,
    head: [columns.map((c) => c.header)],
    body: formattedRows,
    margin: { left: 14, right: 14 },
    theme: 'striped',
    styles: {
      font,
      fontSize: 8,
      cellPadding: 2.2,
      textColor: [30, 41, 59],
      lineColor: [226, 232, 240],
      lineWidth: 0.1,
      overflow: 'linebreak',
    },
    headStyles: {
      fillColor: [5, 150, 105], // Brand Emerald
      textColor: [255, 255, 255],
      fontStyle: 'bold',
      fontSize: 8.5,
    },
    alternateRowStyles: {
      fillColor: [248, 250, 252],
    },
    columnStyles,
    didParseCell: (data) => {
      // Highlight totals row if present at the end
      if (options?.hasTotalsRow && data.section === 'body' && data.row.index === rows.length - 1) {
        data.cell.styles.fontStyle = 'bold';
        data.cell.styles.fillColor = [241, 245, 249];
        data.cell.styles.textColor = [15, 23, 42];
      }
    },
  });

  return (doc as any).lastAutoTable.finalY + 8;
}

/**
 * Stamps footer with page numbers on all pages.
 */
export function addFooters(doc: jsPDF): void {
  const font = fontLoaded ? 'Montserrat' : 'helvetica';
  const totalPages = doc.getNumberOfPages();
  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();

  for (let i = 1; i <= totalPages; i++) {
    doc.setPage(i);
    doc.setFont(font, 'normal');
    doc.setFontSize(8);
    doc.setTextColor(148, 163, 184);

    // Footer divider line
    doc.setDrawColor(226, 232, 240);
    doc.setLineWidth(0.3);
    doc.line(14, pageHeight - 10, pageWidth - 14, pageHeight - 10);

    // Left: Agency signature
    doc.text('Getup Agency Control Panel — Confidential Report', 14, pageHeight - 6);

    // Right: Page numbers
    doc.text(`Page ${i} of ${totalPages}`, pageWidth - 14, pageHeight - 6, { align: 'right' });
  }
}

/**
 * Downloads the PDF directly with standard naming.
 */
export function savePdf(doc: jsPDF, filename: string): void {
  addFooters(doc);
  const cleanName = filename.endsWith('.pdf') ? filename : `${filename}.pdf`;
  doc.save(cleanName);
}

/**
 * Helper to download CSV data.
 */
export function exportToCsv(filename: string, headers: string[], rows: (string | number)[][]): void {
  const escapeCell = (c: string | number) => {
    const val = String(c ?? '').replace(/"/g, '""');
    return `"${val}"`;
  };

  const csvContent = [
    headers.map(escapeCell).join(','),
    ...rows.map((row) => row.map(escapeCell).join(',')),
  ].join('\r\n');

  const blob = new Blob([csvContent], { type: 'text/csv;charset=utf-8;' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename.endsWith('.csv') ? filename : `${filename}.csv`;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}
